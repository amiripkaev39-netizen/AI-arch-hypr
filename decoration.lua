-- decoration.lua
-- Внешний вид окон: скругления, прозрачность, тени, блюр.

hl.config({
    decoration = {
        rounding = 10,               -- радиус скругления углов (в пикселях)
        active_opacity = 1.0,        -- активное окно полностью непрозрачное
        inactive_opacity = 0.95,     -- неактивные окна чуть прозрачные

        -- Тени под окнами
        shadow = {
            enabled = true,
            range = 4,               -- насколько далеко тень уходит от окна
            render_power = 3,        -- "мягкость" тени (1-4)
            color = "rgba(1a1a1aee)", -- цвет тени (почти чёрный)
        },

        -- Размытие фона под полупрозрачными окнами
        blur = {
            enabled = true,
            size = 6,                -- радиус размытия
            passes = 2,              -- количество проходов (больше = мягче, но дороже)
            new_optimizations = true,-- внутренние оптимизации Hyprland
            ignore_opacity = true,   -- блюр работает даже при непрозрачных окнах
            popups = true,           -- блюр для контекстных меню
        },
    },
})
